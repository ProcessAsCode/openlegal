"""jira.* UAPF capabilities - real Jira Cloud REST integration.

create_issue / transition act against the org's enabled jira_cloud Connection.
Non-secret config (base_url, project_key, email) is in Connection.config; the
API token is in Connection.config['api_token'] (POC secret store). With no
connection configured the capability returns created=false + a reason instead
of raising, so a run still completes and the operator sees what's missing.
"""
from __future__ import annotations

import base64

import httpx
from sqlalchemy import select

from openlegal.models.connection import Connection, ConnectionKind


async def _get_conn(session, org):
    stmt = select(Connection).where(
        Connection.org_id == org.id,
        Connection.kind == ConnectionKind.JIRA_CLOUD,
        Connection.is_enabled.is_(True),
    )
    return (await session.execute(stmt)).scalars().first()


def _auth(email, token):
    return "Basic " + base64.b64encode(("%s:%s" % (email, token)).encode()).decode()


async def create_issue(session, org, inputs, context):
    conn = await _get_conn(session, org)
    if conn is None:
        return {"created": False, "reason": "no enabled jira_cloud connection for org " + org.slug}
    cfg = conn.config or {}
    base = (cfg.get("base_url") or "").rstrip("/")
    email = cfg.get("email")
    token = cfg.get("api_token")
    project = inputs.get("project_key") or cfg.get("project_key")
    if not (base and email and token and project):
        return {"created": False, "reason": "jira_cloud connection incomplete (need base_url, email, api_token, project_key)"}
    ob_id = inputs.get("obligation_id") or "obligation"
    action = inputs.get("action") or "create"
    mode = inputs.get("mode") or "auto"
    due = inputs.get("due_date") or ""
    issue_type = inputs.get("jira_issue_type") or "Task"
    summary = inputs.get("summary") or ("[Agreement] %s - %s" % (ob_id, action))
    desc = inputs.get("description") or (
        "Auto-generated by OpenLegal agreement monitoring.\n"
        "Obligation: %s\nAction: %s\nMode: %s\n%sSource package: %s"
        % (ob_id, action, mode, ("Due: %s\n" % due if due else ""),
           context.get("uapf_package_id") or "lv.proc.it_agreement.monitoring"))
    fields = {
        "project": {"key": project},
        "issuetype": {"name": issue_type},
        "summary": summary[:250],
        "description": {"type": "doc", "version": 1, "content": [
            {"type": "paragraph", "content": [{"type": "text", "text": desc}]}]},
    }
    headers = {"Authorization": _auth(email, token),
               "Content-Type": "application/json", "Accept": "application/json"}
    try:
        async with httpx.AsyncClient(timeout=20.0) as c:
            r = await c.post("%s/rest/api/3/issue" % base,
                             json={"fields": fields}, headers=headers)
        if r.status_code >= 300:
            return {"created": False, "reason": "jira %s: %s" % (r.status_code, r.text[:200])}
        data = r.json()
        return {"created": True, "jira_key": data.get("key"), "id": data.get("id"), "mode": mode}
    except Exception as e:
        return {"created": False, "reason": "%s: %s" % (type(e).__name__, e)}


async def transition(session, org, inputs, context):
    conn = await _get_conn(session, org)
    if conn is None:
        return {"transitioned": False, "reason": "no enabled jira_cloud connection"}
    cfg = conn.config or {}
    base = (cfg.get("base_url") or "").rstrip("/")
    email = cfg.get("email")
    token = cfg.get("api_token")
    key = inputs.get("jira_key") or inputs.get("issue_key")
    want = (inputs.get("transition") or inputs.get("to_status") or "").strip()
    if not (base and email and token and key):
        return {"transitioned": False, "reason": "incomplete (need connection + jira_key)"}
    headers = {"Authorization": _auth(email, token),
               "Content-Type": "application/json", "Accept": "application/json"}
    try:
        async with httpx.AsyncClient(timeout=20.0) as c:
            tr = await c.get("%s/rest/api/3/issue/%s/transitions" % (base, key), headers=headers)
            if tr.status_code >= 300:
                return {"transitioned": False, "reason": "jira %s: %s" % (tr.status_code, tr.text[:160])}
            options = tr.json().get("transitions", [])
            tid = None
            for o in options:
                nm = o.get("name", "").lower()
                to = o.get("to", {}).get("name", "").lower()
                if not want or want.lower() in (nm, to):
                    tid = o.get("id")
                    if want:
                        break
            if tid is None and options:
                tid = options[0].get("id")
            if tid is None:
                return {"transitioned": False, "reason": "no transitions available"}
            rr = await c.post("%s/rest/api/3/issue/%s/transitions" % (base, key),
                              json={"transition": {"id": tid}}, headers=headers)
        if rr.status_code >= 300:
            return {"transitioned": False, "reason": "jira %s: %s" % (rr.status_code, rr.text[:160])}
        return {"transitioned": True, "jira_key": key, "transition_id": tid}
    except Exception as e:
        return {"transitioned": False, "reason": "%s: %s" % (type(e).__name__, e)}


