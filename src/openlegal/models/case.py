"""Case model — the long-lived CMMN case container.

In Process-as-Code ITSM, the Case row IS the persistence model for the
running CMMN case execution. There is no separate "ticket" table on top
of process state — the BPMN/CMMN execution log (events table) is the
authoritative timeline, and the Case row carries the current snapshot
of derived fields (status, priority, assignment).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, Enum, ForeignKey, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import JSONB, UUID as PgUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from openlegal.models.base import (
    Base,
    TenantScopedMixin,
    TimestampMixin,
    UUIDPrimaryKeyMixin,
)

if TYPE_CHECKING:
    from openlegal.models.ai_decision import AIDecision
    from openlegal.models.attachment import Attachment
    from openlegal.models.case_event import CaseEvent
    from openlegal.models.comment import Comment
    from openlegal.models.dmn_evaluation import DMNEvaluation
    from openlegal.models.expert_group import ExpertGroup
    from openlegal.models.organization import Organization
    from openlegal.models.signal import Signal
    from openlegal.models.taxonomy import ServiceTier, TaxonomyNode
    from openlegal.models.uapf_execution import UAPFExecution
    from openlegal.models.user import User
    from openlegal.models.vc_reference import VCReference


class CaseStatus(StrEnum):
    """Top-level case status. Maps to CMMN milestone state."""

    OPEN = "open"
    TRIAGED = "triaged"
    IN_PROGRESS = "in_progress"
    WAITING_CUSTOMER = "waiting_customer"
    WAITING_THIRD_PARTY = "waiting_third_party"
    RESOLVED = "resolved"
    CLOSED = "closed"
    CANCELLED = "cancelled"


class CasePriority(StrEnum):
    """Standard P1–P4 priorities."""

    P1 = "P1"
    P2 = "P2"
    P3 = "P3"
    P4 = "P4"


class CaseOwnership(StrEnum):
    """Ownership outcome from `ownership.dmn`."""

    OWN = "own"
    NOT_OWN = "not_own"
    TRANSFERRED = "transferred"


class Case(Base, UUIDPrimaryKeyMixin, TenantScopedMixin, TimestampMixin):
    """One incident / case."""

    __tablename__ = "cases"
    __table_args__ = (
        UniqueConstraint("org_id", "case_number", name="uq_cases_org_id_case_number"),
    )

    # Human-friendly case number, monotonic per org. Generated by the API
    # at case open time (e.g. "DEMO-2026-00001").
    case_number: Mapped[str] = mapped_column(String(32), nullable=False, index=True)

    title: Mapped[str] = mapped_column(String(512), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    status: Mapped[CaseStatus] = mapped_column(
        Enum(CaseStatus, name="case_status", values_callable=lambda x: [e.value for e in x]),
        nullable=False,
        default=CaseStatus.OPEN,
        index=True,
    )
    priority: Mapped[CasePriority | None] = mapped_column(
        Enum(CasePriority, name="case_priority", values_callable=lambda x: [e.value for e in x]),
        nullable=True,
        index=True,
    )
    ownership: Mapped[CaseOwnership | None] = mapped_column(
        Enum(CaseOwnership, name="case_ownership", values_callable=lambda x: [e.value for e in x]),
        nullable=True,
    )

    classification_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey("taxonomy_nodes.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    service_tier_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey("service_tiers.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    assigned_group_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey("expert_groups.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    assigned_user_id: Mapped[uuid.UUID | None] = mapped_column(
        PgUUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # External mirror — Jira ticket key, if mirrored.
    jira_mirror_key: Mapped[str | None] = mapped_column(String(64), nullable=True, index=True)

    # Time-of-life
    opened_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )
    triaged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    first_response_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    closed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    sla_first_response_due_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    sla_resolution_due_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, index=True
    )

    # Convenience snapshot of derived state — full history lives in case_events.
    state_snapshot: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    # Relationships
    organization: Mapped["Organization"] = relationship(back_populates="cases")
    classification: Mapped["TaxonomyNode | None"] = relationship(back_populates="cases")
    service_tier: Mapped["ServiceTier | None"] = relationship(back_populates="cases")
    assigned_group: Mapped["ExpertGroup | None"] = relationship()
    assigned_user: Mapped["User | None"] = relationship()

    signals: Mapped[list["Signal"]] = relationship(back_populates="case")
    events: Mapped[list["CaseEvent"]] = relationship(
        back_populates="case",
        cascade="all, delete-orphan",
        order_by="CaseEvent.created_at",
    )
    comments: Mapped[list["Comment"]] = relationship(
        back_populates="case",
        cascade="all, delete-orphan",
    )
    attachments: Mapped[list["Attachment"]] = relationship(
        back_populates="case",
        cascade="all, delete-orphan",
    )
    ai_decisions: Mapped[list["AIDecision"]] = relationship(back_populates="case")
    dmn_evaluations: Mapped[list["DMNEvaluation"]] = relationship(back_populates="case")
    vc_references: Mapped[list["VCReference"]] = relationship(back_populates="case")
    uapf_executions: Mapped[list["UAPFExecution"]] = relationship(back_populates="case")
